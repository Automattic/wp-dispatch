// Builds the public release log, site/releases/index.html, from each release's notes
// (site/releases/Dispatch-<version>.html, also shown by Sparkle) and its date in site/appcast.xml.
// Usage: node tools/release/log.mjs
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const site = path.join(path.dirname(fileURLToPath(import.meta.url)), "../../site");
const appcast = fs.readFileSync(path.join(site, "appcast.xml"), "utf8");
const releases = [...appcast.matchAll(/<item>[\s\S]*?<\/item>/g)].map(([item]) => ({
  version: item.match(/<sparkle:shortVersionString>([^<]+)/)?.[1],
  date: new Date(item.match(/<pubDate>([^<]+)/)?.[1]),
})).filter((r) => r.version);

// The appcast keeps only the newest few; older releases still have their notes.
for (const file of fs.readdirSync(path.join(site, "releases"))) {
  const version = file.match(/^Dispatch-(\d+\.\d+\.\d+)\.html$/)?.[1];
  if (version && !releases.some((r) => r.version === version)) releases.push({ version, date: null });
}
const parts = (v) => v.split(".").map(Number);
releases.sort((a, b) => { const x = parts(a.version), y = parts(b.version); return y[0] - x[0] || y[1] - x[1] || y[2] - x[2]; });

const notes = (v) => {
  const file = path.join(site, "releases", `Dispatch-${v}.html`);
  if (!fs.existsSync(file)) return "<p>The first release.</p>";
  return fs.readFileSync(file, "utf8").replace(/<h2>[\s\S]*?<\/h2>/, "").trim(); // the page has its own heading
};
const day = (d) => d && !isNaN(d) ? d.toLocaleDateString("en-US", { month: "long", day: "numeric", year: "numeric" }) : "";

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>What's new in Dispatch</title>
<meta name="description" content="Release notes for Dispatch, a menu bar app for WordPress.com.">
<link rel="icon" type="image/png" href="../favicon.png">
<!-- Generated by tools/release/log.mjs from the release notes. Don't edit by hand. -->
<style>
  :root { --bg: #fbfaf8; --text: #1d1d1f; --muted: #6e6e73; --line: #e6e3de; --accent: #3858e9; }
  @media (prefers-color-scheme: dark) { :root { --bg: #141416; --text: #f2f2f4; --muted: #9a9aa2; --line: #2a2a2e; --accent: #7b90ff; } }
  * { box-sizing: border-box; }
  body { margin: 0; background: var(--bg); color: var(--text); font: 17px/1.55 -apple-system, BlinkMacSystemFont, "SF Pro Text", "Helvetica Neue", sans-serif; -webkit-font-smoothing: antialiased; }
  main { max-width: 720px; margin: 0 auto; padding: 64px 20px 72px; }
  a { color: var(--accent); }
  .back { display: inline-flex; align-items: center; gap: 10px; color: var(--muted); text-decoration: none; font-weight: 600; }
  .back img { width: 40px; height: 40px; }
  h1 { font-size: clamp(32px, 5vw, 44px); line-height: 1.1; letter-spacing: -0.02em; margin: 28px 0 8px; }
  .lede { color: var(--muted); margin: 0 0 40px; }
  article { border-top: 1px solid var(--line); padding: 28px 0 8px; }
  article h2 { font-size: 22px; margin: 0; letter-spacing: -0.01em; }
  article time { display: block; color: var(--muted); font-size: 15px; margin-top: 2px; }
  article ul { padding-left: 20px; margin: 14px 0 0; }
  article li { margin: 0 0 8px; }
  article p { margin: 14px 0 0; }
  kbd { font: 600 0.82em/1 -apple-system, sans-serif; padding: 3px 6px; border-radius: 5px; border: 1px solid var(--line); border-bottom-width: 2px; }
</style>
</head>
<body>
<main>
  <a class="back" href="../"><img src="../icon.png" alt="">Dispatch</a>
  <h1>What's new</h1>
  <p class="lede">Every release of Dispatch, newest first. Dispatch updates itself, so you'll get these on your Mac within a day. <a href="../download">Download the latest</a>.</p>
${releases.map((r) => `  <article id="v${r.version}">
    <h2>Dispatch ${r.version}</h2>
    ${r.date ? `<time datetime="${r.date.toISOString().slice(0, 10)}">${day(r.date)}</time>` : ""}
    ${notes(r.version)}
  </article>`).join("\n")}
</main>
</body>
</html>
`;
fs.writeFileSync(path.join(site, "releases", "index.html"), html);
console.log(`Wrote site/releases/index.html (${releases.length} releases)`);
